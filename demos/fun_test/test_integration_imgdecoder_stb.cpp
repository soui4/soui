// SOUI 解码器输出预乘 BGRA：调色板 caf4ca -> ca f4 ca ff，8fd390 -> 90 d3 8f ff，
// tRNS 令索引 0（ffffff）全透明 -> 00 00 00 00。
struct ExpectedPixel { int x, y; unsigned char bgra[4]; };

static const ExpectedPixel kExpected[] = {
    {0,  0, {0xca, 0xf4, 0xca, 0xff}}, // 顶边
    {7,  0, {0xca, 0xf4, 0xca, 0xff}},
    {0,  1, {0xca, 0xf4, 0xca, 0xff}}, // 左边（旧 bug 此处错成透明）
    {1,  1, {0x90, 0xd3, 0x8f, 0xff}}, // 内圈
    {14, 1, {0xca, 0xf4, 0xca, 0xff}}, // 右边
    {2,  2, {0x00, 0x00, 0x00, 0x00}}, // 内部透明区
    {7,  7, {0x00, 0x00, 0x00, 0x00}},
    {13, 7, {0x90, 0xd3, 0x8f, 0xff}},
    {14, 7, {0xca, 0xf4, 0xca, 0xff}},
    {0, 14, {0xca, 0xf4, 0xca, 0xff}}, // 底边（旧 bug 此处逐行漂移最严重）
    {7, 14, {0xca, 0xf4, 0xca, 0xff}},
    {14,14, {0xca, 0xf4, 0xca, 0xff}},
};

