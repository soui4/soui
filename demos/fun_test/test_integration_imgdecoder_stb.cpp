TEST(soui_component, imgdecoder_stb_indexed_png_row_stride)
{
    SComMgr2 comMgr;
#ifdef _WIN32
    SAutoRefPtr<IImgDecoderFactory> decoder;
    ASSERT_TRUE(comMgr.CreateImgDecoder((IObjRef **)&decoder, _T("imgdecoder-stb")));
#else
    SAutoRefPtr<IImgDecoderFactory> decoder;
    ASSERT_TRUE(comMgr.CreateImgDecoder((IObjRef **)&decoder, _T("libimgdecoder-stb")));
#endif
    ASSERT_TRUE(decoder);

    SAutoRefPtr<IImgX> img;
    ASSERT_TRUE(decoder->CreateImgX(&img));
    ASSERT_TRUE(img->LoadFromMemory(kFocusCheckboxPng, sizeof(kFocusCheckboxPng)));
    ASSERT_EQ(img->GetFrameCount(), 1u);

    IImgFrame *frame = img->GetFrame(0);
    ASSERT_TRUE(frame);
    UINT wid = 0, hei = 0;
    ASSERT_TRUE(frame->GetSize(&wid, &hei));
    EXPECT_EQ(wid, 15u);
    EXPECT_EQ(hei, 15u);

    const unsigned char *pixels = (const unsigned char *)frame->GetPixels();
    ASSERT_TRUE(pixels);
    for (size_t i = 0; i < sizeof(kExpected) / sizeof(kExpected[0]); ++i)
    {
        const ExpectedPixel &e = kExpected[i];
        const unsigned char *px = pixels + (e.y * wid + e.x) * 4;
        EXPECT_EQ(px[0], e.bgra[0]) << "pixel (" << e.x << "," << e.y << ") B";
        EXPECT_EQ(px[1], e.bgra[1]) << "pixel (" << e.x << "," << e.y << ") G";
        EXPECT_EQ(px[2], e.bgra[2]) << "pixel (" << e.x << "," << e.y << ") R";
        EXPECT_EQ(px[3], e.bgra[3]) << "pixel (" << e.x << "," << e.y << ") A";
    }
}
