#!/usr/bin/env python3
"""Generate category data, exact XML usage, and the registered-control matrix.

The JSON is the authored catalog, gallery.xml is the live usage source. A stale
header or matrix fails --check; no control counts are inferred from UI variants.
"""
from __future__ import annotations

import argparse
import copy
import json
import xml.etree.ElementTree as ET
from pathlib import Path

DEMO = Path(__file__).resolve().parent


def quote(text):
    return 'L' + json.dumps(text, ensure_ascii=False)


def outputs():
    catalog = json.loads((DEMO / "control_catalog.json").read_text(encoding="utf-8"))
    categories, controls = catalog["categories"], catalog["controls"]
    main = ET.parse(DEMO / "uires/xml/gallery.xml").getroot()
    modal = ET.parse(DEMO / "uires/xml/gallery_modal.xml").getroot()
    native = ET.parse(DEMO / "uires/xml/gallery_native.xml").getroot()
    named = {node.get("name"): node for root in (main, modal, native) for node in root.iter() if node.get("name")}
    keys = [category["key"] for category in categories]
    assert len(keys) == len(set(keys))
    assert len(controls) == len({item["cpp"] for item in controls})
    assert len(controls) == len({item["tag"].lower() for item in controls})
    header = ["// Generated by build_catalog.py; edit control_catalog.json / live XML instead.",
              "#pragma once", "", "namespace Gallery", "{",
              "struct Category { const wchar_t *key, *title, *description, *api; };",
              "inline const Category *Categories()", "{", "    static const Category data[] = {"]
    for category in categories:
        header.append("        { " + ", ".join(quote(category[field]) for field in ("key", "title", "description", "api")) + " },")
    header += ["    };", "    return data;", "}", f"static const int CategoryCount = {len(categories)};",
               "static const int InitialCategory = 5;", "static const int NavigationId = 4100;", "",
               "struct ControlEntry { const wchar_t *cpp, *tag, *sample, *scope; int category; };",
               "inline const ControlEntry *Controls()", "{", "    static const ControlEntry data[] = {"]
    for item in controls:
        assert item["sample"] in named, item["cpp"]
        header.append("        { " + ", ".join(quote(item[field]) for field in ("cpp", "tag", "sample", "scope")) + f', {keys.index(item["category"])}' + " },")
    header += ["    };", "    return data;", "}", f"static const int RegisteredControlCount = {len(controls)};",
               f'static const int LiveControlCount = {sum(c["scope"] != "platform_recipe" for c in controls)};',
               "", "inline const wchar_t *const *Sources()", "{", "    static const wchar_t *data[] = {"]
    markdown = ["# Gallery 内置控件覆盖矩阵", "", "由 `build_catalog.py` 从 `control_catalog.json` 与实际 XML 生成。",
                "", "## 统计口径", "", "- 框架默认注册 **58 类**：57 类无条件注册 + Windows 非 MinGW 的 SActiveX。",
                "- **57 类有真实运行场景**（独立实例、复合子控件或按需创建的模态会话）；SActiveX 仅提供集成用法，不激活外部 COM。",
                "- 同一控件的配色/方向/禁用状态不重复计数。GalleryButton / GalleryTabCtrl / GalleryRebar 为本 Demo 的绘制子类，不算新增内置类。",
                "- Layout、Skin、动画对象以及 controls.extend 不混入此分母。分类依据见 `BUILTIN_CONTROLS.md`。", "",
                "## 查看与运行", "", "选择分类后点 **View XML**，查看从真实示例抽取的 XML；模板和 buddy 引用一起保留。",
                "虚拟视图的完整数据绑定及排序示例在 `GalleryAdapters.h`，事件与会话初始化在 `MainDlg.cpp`。",
                "`live`=独立运行实例；`composite`=真实复合子节点；`dynamic`=按钮启动后实际创建；`platform_recipe`=有前提的用法，不算 live。", ""]
    cpp_usage = {
        "listview": "// C++: Gallery::InitializeViews(root) installs SAdapterBase / SMcAdapterBase adapters.\n// See GalleryAdapters.h for getCount, getView, getItemDesc, OnSort and reference ownership.\n// listctrl->InsertItem(index, title); listctrl->SetSubItemText(index, column, text);",
        "tileview": "// C++: use ILvAdapter::getView(position, itemPanel, xmlTemplate); SetAdapter retains a reference.\n// GalleryAdapters.h binds 30 model rows to the template IDs 1 and 2.",
        "tree": "// C++: GalleryAdapters.h implements STreeAdapterBase node data and expansion.\n// STreeCtrl emits EventTCSelChanged; STreeView emits EventTVSelChanged.",
        "combo": "// C++: SComboView::GetListView()->SetAdapter(adapter).\n// SSearchDropdownList: handle EventDropdownListFill / GetBuddyRect / Selected; see MainDlg.cpp.",
        "dialog": "// C++: new SModalRoot; InitFromResId(layout:gallery_modal); BeginModalViewSession(modal);\n// EndModalViewSession(0, IDOK) closes the active host-managed session.",
        "icons": "// C++: sample_icon->SetIcon(Gallery::CreateVectorIcon(scale)); SIconWnd takes ownership.\n// Vector-to-HICON and native resource lifetimes: GalleryNative.h.",
        "hosting": "// C++: EventRealWndCreate returns a local HWND; EventRealWndDestroy destroys it.\n// SActiveX requires Windows (non-MinGW) and an installed COM server; the gallery activates none.",
        "tabs": "// C++: STabCtrl::SetCurSel(index); SStackView::SelectPage(index, FALSE);\n// Both retain the existing child tree and edit state.",
    }
    for category in categories:
        members = [c for c in controls if c["category"] == category["key"]]
        source = ["<!-- " + category["title"] + " | live SOUI examples -->",
                  "<!-- Shared Fluent defaults: uires/uidef/init.xml; matching light/dark skins: uires/values/. -->"]
        if category["key"] in cpp_usage:
            source.append(cpp_usage[category["key"]])
        if category["key"] == "home":
            source.append("<!-- Browse categories or search a C++ class / XML tag. 58 registered types, 57 runnable scenes. -->")
        markdown += ["## " + category["title"], "", "| C++ 类 | XML 标签 | 样式 / 资源 | 命名实例 | 覆盖 |", "|---|---|---|---|---|"]
        for item in members:
            original = named[item["sample"]]
            sample = copy.deepcopy(original)
            if item["cpp"] in {"SRootWindow", "SCaption", "SScrollView", "STabPage"}:
                sample[:] = []  # Show the host/page contract without duplicating its entire subtree.
            if item["cpp"] in {"SSpinButtonCtrl", "SComboEdit"}:
                parent = next(n for n in main.iter() if original in list(n))
                sample = copy.deepcopy(parent)  # Keep the buddy or editable combobox context.
            if item["cpp"] == "SComboEdit":
                source.append('<!-- SComboEdit is created by combobox dropDown="0"; editStyle is not a standalone control tag. -->')
            if item["scope"] == "platform_recipe":
                source.append('<!-- SActiveX: Windows non-MinGW, installed COM server required. Not activated by this gallery. -->\n<activex clsID="{YOUR-COM-CLSID}" delay="1" size="-2,160dp" />')
            else:
                ET.indent(sample, space="  ")
                source += ["<!-- " + item["cpp"] + " | " + item["style"] + " -->", ET.tostring(sample, encoding="unicode").strip()]
            markdown.append(f'| `{item["cpp"]}` | `{item["tag"]}` | {item["style"]} | `{item["sample"]}` | {item["scope"]} |')
        markdown.append("")
        text = "\n\n".join(source)
        header.append("        " + quote(text) + ",")
    header += ["    };", "    return data;", "}", "} // namespace Gallery", ""]
    return {DEMO / "GalleryCatalog.h": "\n".join(header), DEMO / "CONTROL_COVERAGE.md": "\n".join(markdown)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            if args.check:
                stale.append(path.name)
            else:
                path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale catalog outputs: " + ", ".join(stale))
    print("Gallery catalog / usage / coverage matrix synchronized")


if __name__ == "__main__":
    main()
